FROM SOCIAL_MEDIA_DB_AMS.ANALYTICS.COMMENT_SENTIMENT
GROUP BY
    DATE_TRUNC('HOUR', EVENT_TIMESTAMP),
    SENTIMENT
ORDER BY
    HOUR,
    SENTIMENT;

