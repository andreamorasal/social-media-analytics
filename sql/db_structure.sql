--- trendign hashtags 

INSERT INTO SOCIAL_MEDIA_DB_AMS.ANALYTICS.TRENDING_HASHTAGS
(
    WINDOW_MINUTES,
    HASHTAG,
    EVENT_COUNT,
    RANK,
    WINDOW_START,
    WINDOW_END
)

WITH windows AS (
    SELECT 1 AS WINDOW_MINUTES
    UNION ALL
    SELECT 5
    UNION ALL
    SELECT 15
),

counts AS (
    SELECT
        w.WINDOW_MINUTES,
        c.HASHTAG,
        COUNT(*) AS EVENT_COUNT,

        DATEADD(
            MINUTE,
            -w.WINDOW_MINUTES,
            CURRENT_TIMESTAMP()
        ) AS WINDOW_START,

        CURRENT_TIMESTAMP() AS WINDOW_END

    FROM windows w

    JOIN SOCIAL_MEDIA_DB_AMS.CURATED.CURATED_EVENTS c
        ON c.HASHTAG IS NOT NULL
        AND c.EVENT_TIMESTAMP >= DATEADD(
            MINUTE,
            -w.WINDOW_MINUTES,
            CURRENT_TIMESTAMP()
        )

    GROUP BY
        w.WINDOW_MINUTES,
        c.HASHTAG
),

ranked AS (
    SELECT
        WINDOW_MINUTES,
        HASHTAG,
        EVENT_COUNT,

        ROW_NUMBER() OVER (
            PARTITION BY WINDOW_MINUTES
            ORDER BY EVENT_COUNT DESC
        ) AS RANK,

        WINDOW_START,
        WINDOW_END

    FROM counts
)

SELECT
    WINDOW_MINUTES,
    HASHTAG,
    EVENT_COUNT,
    RANK,
    WINDOW_START,
    WINDOW_END

FROM ranked

WHERE RANK <= 10;


